#!/usr/bin/env python3
"""Writes packages/host/src/base/binaries.ts: the executables an Ubuntu 24.04 server's base
packages install, with their sizes, modes and symlink targets, read from this workstation.

The workstation runs these Ubuntu packages at the versions listed in PACKAGES (docs/FIDELITY.md
§2.1; `dpkg-query -W` checks each). Pop!_OS changes none of them. Alternatives links are written
as a stock server has them (awk -> mawk), not as this workstation has them (awk -> gawk).

Run: python3 tools/src/base/capture_binaries.py > packages/host/src/base/binaries.ts
"""

import json
import os
import subprocess
import sys

PACKAGES = ["bash", "coreutils", "dash", "debianutils", "diffutils", "findutils", "grep", "gzip",
            "hostname", "less", "mawk", "ncurses-bin", "sed", "tar"]
# update-alternatives links a stock Ubuntu 24.04 server has for these packages.
ALTERNATIVES = {"/usr/bin/awk": "awk", "/usr/bin/which": "which"}
ALT_TARGETS = {"awk": "/usr/bin/mawk", "which": "/usr/bin/which.debianutils"}
# Stubs whose program has another registry name. which.debianutils is a /bin/sh script; it is
# simulated as the program `which` (docs/FIDELITY.md DIV-001). Other scripts keep their text.
PROGRAM_NAME = {"which.debianutils": "which"}


def main():
    entries = {}
    versions = {}
    for pkg in PACKAGES:
        versions[pkg] = subprocess.run(["dpkg-query", "-W", "-f=${Version}", pkg], capture_output=True, text=True, check=True).stdout
        files = subprocess.run(["dpkg", "-L", pkg], capture_output=True, text=True, check=True).stdout.split("\n")
        for f in files:
            if not (f.startswith("/usr/bin/") or f.startswith("/usr/sbin/") or f.startswith("/bin/") or f.startswith("/sbin/")):
                continue
            path = "/usr" + f if f.startswith("/bin/") or f.startswith("/sbin/") else f
            if path.count("/") != 3 or not os.path.lexists(path):
                continue
            st = os.lstat(path)
            if os.path.islink(path):
                entries[path] = ("link", os.readlink(path), pkg)
            else:
                with open(path, "rb") as fh:
                    head = fh.read(2)
                base = os.path.basename(path)
                if head == b"#!" and base not in PROGRAM_NAME:
                    with open(path, encoding="utf-8") as fh:
                        entries[path] = ("script", (fh.read(), st.st_mode & 0o7777), pkg)
                else:
                    entries[path] = ("file", (st.st_size, st.st_mode & 0o7777), pkg)
    for link, name in ALTERNATIVES.items():
        entries[link] = ("link", "/etc/alternatives/" + name, "alternatives")
    out = []
    out.append("// Executables of an Ubuntu 24.04 server's base packages: stubs naming a program, and symlinks.")
    out.append("// Generated by tools/src/base/capture_binaries.py from the workstation's packages; do not edit.")
    out.append("// reference: " + ", ".join("%s %s" % (p, versions[p]) for p in PACKAGES))
    out.append("")
    out.append("/** path, then [size, mode, program] for a stub, {script, mode} for a script, or the target of a symlink. */")
    out.append("export const BINARIES: [string, [number, number, string] | { script: string; mode: number } | string][] = [")
    for path in sorted(entries):
        kind, data, pkg = entries[path]
        if kind == "file":
            size, mode = data
            base = os.path.basename(path)
            out.append("  [%s, [%d, 0o%o, %s]]," % (json.dumps(path), size, mode, json.dumps(PROGRAM_NAME.get(base, base))))
        elif kind == "script":
            text, mode = data
            out.append("  [%s, { script: %s, mode: 0o%o }]," % (json.dumps(path), json.dumps(text), mode))
        else:
            out.append("  [%s, %s]," % (json.dumps(path), json.dumps(data)))
    out.append("];")
    out.append("")
    out.append("/** /etc/alternatives links: name -> target. */")
    out.append("export const ALTERNATIVES: [string, string][] = [")
    for name in sorted(ALT_TARGETS):
        out.append("  [%s, %s]," % (json.dumps(name), json.dumps(ALT_TARGETS[name])))
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    main()
