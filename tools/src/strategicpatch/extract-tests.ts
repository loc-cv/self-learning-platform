// node tools/src/strategicpatch/extract-tests.ts [--check]
//
// Copies the test tables of upstream's strategic merge patch tests into the engine's tests:
// .upstream/kubernetes/staging/src/k8s.io/apimachinery/pkg/util/strategicpatch/patch_test.go
// (v1.37.2) → packages/k8s/src/apimachinery/strategicpatch/testdata/patch_test.data.ts. The YAML
// documents are kept as text; the tests decode them with the engine's sigs.k8s.io/yaml port, as
// upstream's tests do with sigs.k8s.io/yaml. Needs `npm run upstream:fetch`; `--check` fails
// when the copy differs from what upstream has.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { repoRoot } from '../oracle/paths.ts';

const source = path.join(repoRoot, '.upstream/kubernetes/staging/src/k8s.io/apimachinery/pkg/util/strategicpatch/patch_test.go');
const target = path.join(repoRoot, 'packages/k8s/src/apimachinery/strategicpatch/testdata/patch_test.data.ts');
const go = readFileSync(source, 'utf8');

/** `var <name> = []byte(\`…\`)` */
function yamlBlock(name: string): string {
  const m = new RegExp(`var ${name} = \\[\\]byte\\(\`([^\`]*)\`\\)`).exec(go);
  if (!m) throw new Error(`no ${name} in patch_test.go`);
  return m[1] as string;
}

/** The body of `var <name> = []StrategicMergePatchRawTestCase{ … }` split into its cases. */
function rawCases(name: string): Record<string, string>[] {
  const start = go.indexOf(`var ${name} = []StrategicMergePatchRawTestCase{`);
  if (start < 0) throw new Error(`no ${name} in patch_test.go`);
  const end = go.indexOf('\n}\n', start);
  const body = go.slice(start, end);
  return body
    .split(/\n\t\{\n\t\tDescription: /)
    .slice(1)
    .map((chunk) => {
      const out: Record<string, string> = {};
      const d = /^("(?:[^"\\]|\\.)*")/.exec(chunk);
      if (!d) throw new Error(`bad case in ${name}: ${chunk.slice(0, 80)}`);
      out.description = JSON.parse(d[1] as string) as string;
      for (const f of chunk.matchAll(/\b(Original|Modified|Current|TwoWay|ThreeWay|Result|TwoWayResult): \[\]byte\(`([^`]*)`\)/g)) out[(f[1] as string).charAt(0).toLowerCase() + (f[1] as string).slice(1)] = f[2] as string;
      const e = /ExpectedError: ("(?:[^"\\]|\\.)*")/.exec(chunk);
      if (e) out.expectedError = JSON.parse(e[1] as string) as string;
      return out;
    });
}

/** The map literal of a `func <name>(t *testing.T)` table: `"key": { Field: \`…\`, … }`. */
function goTable(func: string): Record<string, Record<string, string>> {
  const start = go.indexOf(`func ${func}(t *testing.T) {`);
  if (start < 0) throw new Error(`no ${func} in patch_test.go`);
  const end = go.indexOf('\n\t}\n', start);
  const body = go.slice(start, end);
  const out: Record<string, Record<string, string>> = {};
  for (const m of body.matchAll(/\n\t\t("(?:[^"\\]|\\.)*"): \{([\s\S]*?)\n\t\t\},/g)) {
    const fields: Record<string, string> = {};
    for (const f of (m[2] as string).matchAll(/(\w+):\s+`([^`]*)`/g)) fields[f[1] as string] = f[2] as string;
    out[JSON.parse(m[1] as string) as string] = fields;
  }
  return out;
}

const data = {
  sortMergeListTestCaseData: yamlBlock('sortMergeListTestCaseData'),
  customStrategicMergePatchTestCaseData: yamlBlock('customStrategicMergePatchTestCaseData'),
  createStrategicMergePatchTestCaseData: yamlBlock('createStrategicMergePatchTestCaseData'),
  customStrategicMergePatchRawTestCases: rawCases('customStrategicMergePatchRawTestCases'),
  strategicMergePatchRawTestCases: rawCases('strategicMergePatchRawTestCases'),
  replaceRawExtensionPatchTestCases: rawCases('replaceRawExtensionPatchTestCases'),
  unknownFieldTestCases: goTable('TestUnknownField'),
};

const text = `// Generated by tools/src/strategicpatch/extract-tests.ts from upstream's
// staging/src/k8s.io/apimachinery/pkg/util/strategicpatch/patch_test.go (Kubernetes v1.37.2,
// Apache License 2.0). Do not edit.

export interface RawTestCase {
  description: string;
  original?: string;
  modified?: string;
  current?: string;
  twoWay?: string;
  threeWay?: string;
  result?: string;
  twoWayResult?: string;
  expectedError?: string;
}

export const DATA: {
  sortMergeListTestCaseData: string;
  customStrategicMergePatchTestCaseData: string;
  createStrategicMergePatchTestCaseData: string;
  customStrategicMergePatchRawTestCases: RawTestCase[];
  strategicMergePatchRawTestCases: RawTestCase[];
  replaceRawExtensionPatchTestCases: RawTestCase[];
  unknownFieldTestCases: Record<string, Record<string, string>>;
} = ${JSON.stringify(data, null, 1)};
`;

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== text) {
    console.error(`${path.relative(repoRoot, target)} differs from upstream's tables; run node tools/src/strategicpatch/extract-tests.ts`);
    process.exit(1);
  }
  console.log('strategic merge patch test tables match upstream');
} else {
  writeFileSync(target, text);
  console.log(`wrote ${path.relative(repoRoot, target)}: ${data.strategicMergePatchRawTestCases.length} raw cases, ${Object.keys(data.unknownFieldTestCases).length} unknown-field cases`);
}
